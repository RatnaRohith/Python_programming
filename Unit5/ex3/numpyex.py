import numpy as np

# Create a NumPy array
arr = np.array([[10, 20, 30],
                [40, 50, 60]])

# Display the array
print("Array:")
print(arr)

# Display number of dimensions
print("Number of dimensions (ndim):", arr.ndim)

# Display shape of the array
print("Shape of the array (shape):", arr.shape)

# Display total number of elements
print("Number of elements (size):", arr.size)

# Display data type of elements
print("Data type of elements (dtype):", arr.dtype)