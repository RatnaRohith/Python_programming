import numpy as np

# Create a NumPy array
arr = np.array([10, 20, 30, 40, 50])

print("Array:")
print(arr)

# Find minimum value
print("Minimum value:", np.min(arr))

# Find maximum value
print("Maximum value:", np.max(arr))

# Find sum of elements
print("Sum of elements:", np.sum(arr))

# Find cumulative sum
print("Cumulative sum:", np.cumsum(arr))