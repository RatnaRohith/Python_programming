# Program to demonstrate 5 built-in functions on a list

numbers = [40, 10, 50, 20, 30]

print("Original List:", numbers)

# 1. len() - returns the number of elements
print("Length:", len(numbers))

# 2. max() - returns the largest element
print("Maximum:", max(numbers))

# 3. min() - returns the smallest element
print("Minimum:", min(numbers))

# 4. sum() - returns the sum of all elements
print("Sum:", sum(numbers))

# 5. sorted() - returns the list in sorted order
print("Sorted List:", sorted(numbers))