# Program to demonstrate assignment operators

a = 10
print("Initial value of a:", a)

# Simple assignment
a = 20
print("After = :", a)

# Addition assignment
a += 5
print("After += 5:", a)

# Subtraction assignment
a -= 3
print("After -= 3:", a)

# Multiplication assignment
a *= 2
print("After *= 2:", a)

# Division assignment
a /= 4
print("After /= 4:", a)

# Floor division assignment
a //= 2
print("After //= 2:", a)

# Modulus assignment
a %= 3
print("After %= 3:", a)

# Exponentiation assignment
a **= 2
print("After **= 2:", a)