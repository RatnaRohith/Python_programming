# Program to demonstrate arithmetic operators

a = 20
b = 6

print("First number:", a)
print("Second number:", b)

# Addition
print("\nAddition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Floor Division
print("Floor Division:", a // b)

# Modulus
print("Modulus:", a % b)

# Exponentiation
print("Exponentiation:", a ** b)