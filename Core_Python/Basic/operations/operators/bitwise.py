# Program to demonstrate bitwise operators

a = 10
b = 4

print("a =", a)
print("b =", b)

# Binary representation
print("\nBinary representation:")
print("a =", bin(a))
print("b =", bin(b))

# Bitwise AND
print("\nBitwise AND (a & b):", a & b)

# Bitwise OR
print("Bitwise OR (a | b):", a | b)

# Bitwise XOR
print("Bitwise XOR (a ^ b):", a ^ b)

# Bitwise NOT
print("Bitwise NOT (~a):", ~a)

# Left Shift
print("Left Shift (a << 2):", a << 2)

# Right Shift
print("Right Shift (a >> 2):", a >> 2)