# Program to demonstrate comparison operators

a = 10
b = 20

print("a =", a)
print("b =", b)

# Equal to
print("\nEqual to (==):", a == b)

# Not equal to
print("Not equal to (!=):", a != b)

# Greater than
print("Greater than (>):", a > b)

# Less than
print("Less than (<):", a < b)

# Greater than or equal to
print("Greater than or equal to (>=):", a >= b)

# Less than or equal to
print("Less than or equal to (<=):", a <= b)