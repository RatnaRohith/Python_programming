# Program to demonstrate membership operators

numbers = [10, 20, 30, 40, 50]

# Using 'in' operator
print("30 in numbers:", 30 in numbers)
print("60 in numbers:", 60 in numbers)

# Using 'not in' operator
print("30 not in numbers:", 30 not in numbers)
print("60 not in numbers:", 60 not in numbers)

# Membership operators with strings
name = "Python"

print("'P' in name:", 'P' in name)
print("'z' not in name:", 'z' not in name)
