# Program to demonstrate different types of numbers in Python

# 1. Integer
a = 25
print("Integer:")
print("Value:", a)
print("Type:", type(a))

# 2. Float
b = 12.5
print("\nFloat:")
print("Value:", b)
print("Type:", type(b))

# 3. Complex number
c = 5 + 3j
print("\nComplex number:")
print("Value:", c)
print("Type:", type(c))

# Arithmetic operations
x = 20
y = 6

print("\nArithmetic Operations:")
print("Addition:", x + y)
print("Subtraction:", x - y)
print("Multiplication:", x * y)
print("Division:", x / y)
print("Floor Division:", x // y)
print("Modulus:", x % y)
print("Exponent:", x ** y)

# Complex number operations
z = 2 + 3j
print("\nComplex Number Operations:")
print("Real part:", z.real)
print("Imaginary part:", z.imag)
print("Conjugate:", z.conjugate())

