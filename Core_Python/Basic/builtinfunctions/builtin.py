# Program to demonstrate built-in functions

numbers = [10, 20, 30, 40, 50]

# len() - returns the number of elements
print("Length:", len(numbers))

# max() - returns the largest value
print("Maximum:", max(numbers))

# min() - returns the smallest value
print("Minimum:", min(numbers))

# sum() - returns the sum of elements
print("Sum:", sum(numbers))

# sorted() - sorts the elements
print("Sorted:", sorted(numbers, reverse=True))

# type() - returns the data type
print("Type:", type(numbers))

# abs() - returns the absolute value
print("Absolute value:", abs(-25))

# pow() - calculates power
print("Power:", pow(2, 3))

# round() - rounds a number
print("Rounded value:", round(15.678, 2))

# int() - converts to integer
print("Integer:", int(25.8))

# float() - converts to float
print("Float:", float(25))

# str() - converts to string
print("String:", str(100))